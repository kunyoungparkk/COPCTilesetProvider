// Renders the notices the published bundles owe their dependencies.
//
// `dist/index.js` and `dist/worker.js` inline copc, laz-perf and proj4 rather
// than importing them, so what ships is partly their code. MIT asks that its
// copyright notice travel with every substantial portion; Apache-2.0 asks for
// a copy of the license. Minification strips the headers that would have
// carried either, measured: the published 0.2.0 bundles contain no MIT notice
// at all. This file is how the obligation is met instead.
//
// Regenerate into the repository:
//   node build/third-party-notices.mjs THIRD-PARTY-NOTICES.md
// The build writes its own copy into dist/, and `tests/manifest.test.ts` fails
// when the committed one no longer matches the installed packages — which is
// what makes a dependency bump remember this file.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../', import.meta.url);

/** The canonical text of a license a package names but does not ship. */
const CANONICAL = {
  'Apache-2.0': 'https://www.apache.org/licenses/LICENSE-2.0',
};

/**
 * The license text a package ships, or `undefined`.
 *
 * Matched case-insensitively and without assuming an extension: copc ships
 * `license`, proj4 ships `LICENSE.md`, and neither convention is a rule.
 */
function shippedLicense(packageDir) {
  const names = readdirSync(packageDir).filter((name) =>
    /^(licence|license|copying|notice)(\..*)?$/i.test(name),
  );
  const first = names.sort()[0];
  // A plain path, not a `new URL(...)`: `packageDir` is already an absolute
  // filesystem path (its caller ran it through `fileURLToPath`), and on
  // Windows that starts `C:\`, which the URL parser reads as the scheme `c:`
  // — `TypeError: The URL must be of scheme file`, before any license is
  // read. `readdirSync` above and the `package.json` read below both take the
  // path directly; this line was the one that did not.
  return first === undefined ? undefined : readFileSync(`${packageDir}/${first}`, 'utf8').trim();
}

function section(name) {
  const dir = fileURLToPath(new URL(`node_modules/${name}`, ROOT));
  const manifest = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'));
  const { version, license } = manifest;
  const text = shippedLicense(dir);

  const heading = `## ${name} ${version} — ${license}`;
  if (text !== undefined) {
    return `${heading}\n\n\`\`\`\n${text}\n\`\`\`\n`;
  }
  const canonical = CANONICAL[license];
  return (
    `${heading}\n\n` +
    `This package ships no license file of its own; \`${license}\` is what its\n` +
    `\`package.json\` declares. The canonical text of that license is at\n` +
    `${canonical ?? 'its own project page'}.\n`
  );
}

/** The whole notices document, for the dependencies the manifest declares. */
export function renderNotices() {
  const manifest = JSON.parse(readFileSync(fileURLToPath(new URL('package.json', ROOT)), 'utf8'));
  const names = Object.keys(manifest.dependencies).sort();

  return (
    '# Third-party notices\n\n' +
    '`copc-tileset-provider` bundles its runtime dependencies into the files it\n' +
    'publishes — `dist/index.js` and `dist/worker.js` contain their code rather\n' +
    'than importing it — so their licenses travel with this package.\n\n' +
    'Generated by `build/third-party-notices.mjs` from the installed packages.\n' +
    'Do not edit by hand.\n\n' +
    `${names.map(section).join('\n')}`
  );
}

if (process.argv[1]?.endsWith('third-party-notices.mjs')) {
  const out = process.argv[2];
  if (out === undefined) {
    throw new Error('usage: node build/third-party-notices.mjs <output-path>');
  }
  writeFileSync(out, renderNotices());
  console.log(`third-party notices written to ${out}`);
}
